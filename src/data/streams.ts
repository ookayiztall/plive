export const getStreamBySlug = (slug: string) => mockStreams.find((s) => s.slug === slug);
export const getStreamById = (id: string) => mockStreams.find((s) => s.id === id);
export const getLiveStreams = () => mockStreams.filter((s) => s.status === "live" && s.isActive);
export const getUpcomingStreams = () =>
  mockStreams
    .filter((s) => s.status === "scheduled" && s.isActive)
    .sort((a, b) => (a.startsAt ?? "").localeCompare(b.startsAt ?? ""));
export const getChannels = () => mockStreams.filter((s) => s.type === "channel" && s.isActive);
export const getStreamsByCategory = (categoryId: string) =>
  mockStreams.filter((s) => s.categoryId === categoryId);
